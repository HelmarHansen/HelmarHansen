def _big_norm(s):
    return "".join(c if c in BIG else " " for c in str(s))


def big_width(s, scale=1):
    s = _big_norm(s)
    if not s:
        return 0
    return (sum(len(BIG[c][0]) + 1 for c in s) - 1) * scale


def big_path_d(s, x, y, scale=1, grow=0):
    """Große Ziffern (7 Pixel hoch). y ist die Oberkante. Mit grow > 0 entsteht ein Leuchtrand."""
    s = _big_norm(s)
    d = []
    cx = x
    g = grow
    for ch in s:
        rows = BIG[ch]
        w = len(rows[0])
        for r, row in enumerate(rows):
            c = 0
            while c < w:
                if row[c] == "#":
                    start = c
                    while c < w and row[c] == "#":
                        c += 1
                    rw = (c - start) * scale + 2 * g
                    d.append(f"M{cx + start * scale - g:g} {y + r * scale - g:g}h{rw:g}v{scale + 2 * g:g}h-{rw:g}z")
                else:
                    c += 1
        cx += (w + 1) * scale
    return "".join(d)
